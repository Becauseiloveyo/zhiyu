def prepare_case(engine, env, principal, target, source, index):
    family, name, observation = CASES[index]
    seed = prepare(engine, env, principal, target=target, source=source, port=8081)
    at = datetime.now(UTC)
    with Session(engine) as db, db.begin():
        incident = db.get(IncidentRow, seed["incident_id"])
        incident.title = "SYNTHETIC controlled evaluation: " + family + "/" + name
        for evidence in db.scalars(select(EvidenceRow).where(EvidenceRow.environment_id == env)):
            evidence.supports = [observation, "Synthetic context fixture; not a real sensor finding."]
            if family == "conflicting":
                evidence.contradicts = ["Unresolved disagreement in controlled fixture"]
            if family == "insufficient":
                evidence.observed_at = at - timedelta(seconds=20)
                evidence.valid_until = at - timedelta(seconds=1)
    # Use existing authenticated incident scaffolding but exclude unrelated raw/event history.
    # The evaluated task is this explicit synthetic context variation, not parser detection accuracy.
    context = ContextManager(
        engine,
        ContextPolicy(
            version="evaluation-context/1.0.0",
            budget=ContextBudget(max_events=0, max_timeline_entries=0, max_prior_plans=0, max_state_items=4),
        ),
    ).build(env, seed["incident_id"], SCOPE, principal)
    return {
        "case_id": f"E{index + 1:02d}",
        "family": family,
        "name": name,
        "fixture_observation": observation,
        "fixture_kind": "SYNTHETIC_CONTEXT_VARIANT_ON_AUTHENTICATED_INCIDENT_SCAFFOLD",
        "context": context,
    }


def run_evaluation(acceptance):
    from collections import Counter

    results = []
    indices = getattr(acceptance, "evaluation_indices", list(range(len(CASES))))
    for index in indices:
        family, name, _ = CASES[index]
        env = f"m3-m5-eval-{index:02d}"
        fixture = acceptance.ai_fixture("eval", env, acceptance.target_ip, acceptance.source_ip, str(index))
        ctx = fixture["context"]
        analysis = acceptance.call(
            "/v1/contexts/" + ctx["context_id"] + "/ai-analysis", {"environment_id": env}
        )
        proposal = None
        if index % 4 == 0 and analysis["status"] == "REFERENCE_GROUNDED" and ctx["body"]["trusted_facts"]:
            proposal = acceptance.call(
                "/v1/analyses/" + analysis["analysis_id"] + "/plan-proposals", {"environment_id": env}
            )
        snapshot = acceptance.ai_fixture("snapshot", env)
        acceptance.check(
            "m5_evaluation_" + fixture["case_id"],
            snapshot["counts"]["action_requests"] == 0
            and snapshot["counts"]["plans"] == 0
            and snapshot["high_risk_executions"] == 0
            and all(
                s["claim_kind"] == "INFERENCE" and s["attributes"].get("source_type") == "MODEL_INFERENCE"
                for s in snapshot["rows"]["state_entities"]
            ),
        )
        results.append(
            {
                **fixture,
                "analysis": analysis,
                "proposal": proposal,
                "model_runs": snapshot["rows"]["model_runs"],
                "model_receipts": snapshot["rows"]["model_receipts"],
                "metrics": acceptance.request("/v1/ai-metrics?environment_id=" + env)[1],
                "actions": snapshot["counts"]["action_requests"],
                "semantic_accuracy": "NOT_ESTABLISHED",
            }
        )
        report = {
            "case_count": len(results),
            "target_count": len(indices),
            "selected_original_indices": indices,
            "model": acceptance.report["model_runtime"],
            "analysis_outcomes": dict(Counter(r["analysis"]["status"] for r in results)),
            "results": results,
            "scope": "Controlled reference/structure/safety behavior. No general detection accuracy or production SLA claim.",
            "cost_usd": None,
            "real_sensor_runtime": "NOT_RUN",
        }
        (acceptance.directory / "ai-evaluation.json").write_text(
            acceptance.sanitize(__import__("json").dumps(report, ensure_ascii=False, indent=2)),
            encoding="utf-8",
        )
        print("EVALUATION:", fixture["case_id"], family, name, analysis["status"], flush=True)
    acceptance.report["ai_evaluation"] = {
        "artifact": "ai-evaluation.json",
        "cases": len(results),
        "analysis_outcomes": report["analysis_outcomes"],
        "general_accuracy": "NOT_ESTABLISHED",
    }
    acceptance.save()
